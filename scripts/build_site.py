"""Build the static site for GitHub Pages from guia-bebe.html.

guia-bebe.html is authored for the claude.ai artifact viewer, which wraps it in a
document skeleton. This script adds that skeleton (doctype, head, base reset) plus a
web app manifest, icons, self-hosted fonts and a service worker so the course can be
installed on a phone and read without a connection (hospital wards often have poor signal).
"""
import hashlib
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "guia-bebe.html"
OUT = ROOT / "docs"
VIDEOS = ROOT / "videos"
ASSETS = ROOT / "assets"
GOOGLE_FONTS_RE = re.compile(r'<link rel="preconnect" href="https://fonts.googleapis.com">\n<link rel="stylesheet" href="https://fonts.googleapis.com/[^"]+">\n')
LOCAL_FONTS = """<link rel="preload" href="fonts/atkinson-400.woff2" as="font" type="font/woff2" crossorigin>
<style>
@font-face{font-family:"Atkinson Hyperlegible";font-style:normal;font-weight:400;font-display:swap;src:url(fonts/atkinson-400.woff2) format("woff2")}
@font-face{font-family:"Atkinson Hyperlegible";font-style:italic;font-weight:400;font-display:swap;src:url(fonts/atkinson-400-italic.woff2) format("woff2")}
@font-face{font-family:"Atkinson Hyperlegible";font-style:normal;font-weight:700;font-display:swap;src:url(fonts/atkinson-700.woff2) format("woff2")}
@font-face{font-family:"Bricolage Grotesque";font-style:normal;font-weight:500 700;font-display:swap;src:url(fonts/bricolage.woff2) format("woff2")}
</style>
"""
SW_REGISTER = """<script>
if ("serviceWorker" in navigator) addEventListener("load", () => navigator.serviceWorker.register("sw.js").catch(() => {}));
</script>
"""
SPLIT_MARKER = '<div class="wrap">'

HEAD_EXTRA = """<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#f3f5f7" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#121722" media="(prefers-color-scheme: dark)">
<meta name="description" content="Curso por píldoras para padres primerizos.">
<meta name="robots" content="noindex">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="icon-180.png">
<style>
:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}
body{margin:0}
img{max-width:100%}
[hidden]{display:none!important}
</style>
"""

MANIFEST = """{
  "name": "Bebé en Camino",
  "short_name": "Bebé en Camino",
  "lang": "es",
  "start_url": "./",
  "display": "standalone",
  "background_color": "#f3f5f7",
  "theme_color": "#2f6f8f",
  "icons": [
    {"src": "icon.svg", "sizes": "any", "type": "image/svg+xml"},
    {"src": "icon-180.png", "sizes": "180x180", "type": "image/png"},
    {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
    {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
    {"src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}
  ],
  "shortcuts": [
    {"name": "SOS: qué está pasando", "short_name": "SOS", "url": "./#ayuda", "icons": [{"src": "icon-192.png", "sizes": "192x192"}]},
    {"name": "Buscar una duda", "short_name": "Buscar", "url": "./#buscar", "icons": [{"src": "icon-192.png", "sizes": "192x192"}]}
  ]
}
"""

ICON_SVG = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 180 180">
<rect width="180" height="180" rx="40" fill="#2f6f8f"/>
<circle cx="70" cy="86" r="34" fill="#f1dcc4"/>
<path d="M36 86a34 34 0 0 1 22-32q-9 18-5 32q-4 14 5 32a34 34 0 0 1-22-32z" fill="#8a5a2c"/>
<rect x="96" y="62" width="58" height="48" rx="20" fill="#f3f5f7"/>
<rect x="40" y="132" width="100" height="10" rx="5" fill="#b76a1f"/>
</svg>
"""


SERVICE_WORKER = """/* Generated by scripts/build_site.py */
const CACHE = "bebe-__VERSION__";
const CORE = __CORE__;
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  /* Videos use range requests: leave them to the network. */
  if (req.url.endsWith(".mp4")) return;
  if (req.mode === "navigate") {
    /* Network first so updates arrive; the cached page when there is no signal. */
    e.respondWith(fetch(req).then(r => { const copy = r.clone(); caches.open(CACHE).then(c => c.put("./", copy)); return r; })
      .catch(() => caches.match("./").then(r => r || caches.match("index.html"))));
    return;
  }
  e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(r => {
    if (r.ok) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return r;
  })));
});
"""


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8")
    head_part, sep, body_part = source.partition(SPLIT_MARKER)
    if not sep:
        raise SystemExit(f"Marker {SPLIT_MARKER!r} not found in {SOURCE.name}")
    # The artifact-only viewport hint is meaningless outside claude.ai.
    head_part = head_part.replace('<meta name="claude:viewport-fit-sides" content="cover">\n', "")
    head_part, n = GOOGLE_FONTS_RE.subn(LOCAL_FONTS, head_part)
    if n != 1:
        raise SystemExit("Google Fonts link not found: self-hosted fonts not applied")
    html = (
        "<!doctype html>\n<html lang=\"es\">\n<head>\n"
        + HEAD_EXTRA
        + head_part.strip()
        + "\n</head>\n<body>\n"
        + SPLIT_MARKER
        + body_part.rstrip()
        + "\n"
        + SW_REGISTER
        + "</body>\n</html>\n"
    )
    OUT.mkdir(exist_ok=True)
    (OUT / "index.html").write_text(html, encoding="utf-8")
    (OUT / "manifest.webmanifest").write_text(MANIFEST, encoding="utf-8")
    (OUT / "icon.svg").write_text(ICON_SVG, encoding="utf-8")
    (OUT / ".nojekyll").write_text("", encoding="utf-8")
    if VIDEOS.is_dir():
        shutil.copytree(VIDEOS, OUT / "videos", dirs_exist_ok=True)
    shutil.copytree(ASSETS / "fonts", OUT / "fonts", dirs_exist_ok=True)
    for icon in ASSETS.glob("icon-*.png"):
        shutil.copy2(icon, OUT / icon.name)
    core = ["./", "index.html", "manifest.webmanifest", "icon.svg", "icon-180.png", "icon-192.png", "icon-512.png"]
    core += [f"fonts/{f.name}" for f in sorted((OUT / "fonts").glob("*.woff2"))]
    core += [f"videos/{f.name}" for f in sorted((OUT / "videos").glob("*.jpg"))]
    digest = hashlib.sha256()
    for name in core[1:]:
        digest.update((OUT / name).read_bytes())
    sw = SERVICE_WORKER.replace("__VERSION__", digest.hexdigest()[:12]).replace("__CORE__", repr(core).replace("'", '"'))
    (OUT / "sw.js").write_text(sw, encoding="utf-8")
    print(f"Built {OUT / 'index.html'} ({len(html) // 1024} KB)")


if __name__ == "__main__":
    main()
